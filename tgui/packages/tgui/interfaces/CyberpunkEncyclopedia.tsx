export function CyberpunkEncyclopedia() {
  const [query, setQuery] = useState('');
  const [selected, setSelected] = useState(topics[0].title);
  const needle = query.trim().toLowerCase();
  const matches = topics.filter(({ title, entries }) =>
    [title, ...entries].some((value) => value.toLowerCase().includes(needle)),
  );
  const topic = matches.find(({ title }) => title === selected) ?? matches[0];

  return (
    <Window title="Энциклопедия Брайт-Сити" width={720} height={490}>
      <Window.Content scrollable>
        <Stack vertical fill>
          <Stack.Item>
            <Input
              fluid
              placeholder="Поиск по энциклопедии"
              value={query}
              onChange={setQuery}
            />
          </Stack.Item>
          <Stack.Item grow>
            <Stack fill>
              <Stack.Item width="190px">
                <Section>
                  {matches.map(({ title }) => (
                    <Button
                      fluid
                      key={title}
                      selected={topic?.title === title}
                      onClick={() => setSelected(title)}
                    >
                      {title}
                    </Button>
                  ))}
                </Section>
              </Stack.Item>
              <Stack.Item grow>
                <Section title={topic?.title} fill>
                  {topic ? (
                    <ul>
                      {topic.entries.map((entry) => (
                        <li key={entry}>{entry}</li>
                      ))}
                    </ul>
                  ) : (
                    'По этому запросу ничего не найдено.'
                  )}
                </Section>
              </Stack.Item>
            </Stack>
          </Stack.Item>
        </Stack>
      </Window.Content>
    </Window>
  );
}
